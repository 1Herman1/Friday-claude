// Local snapshot-only regression. No production requests or writes.
import assert from 'node:assert/strict'
const {chromium, webkit} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core')
const base = new URL(process.env.PS_E2E_BASE_URL || 'http://127.0.0.1:5192')
assert(['localhost','127.0.0.1','[::1]'].includes(base.hostname))
const engine = process.env.ENGINE || 'chromium'
const browser = await ({chromium,webkit}[engine]).launch({headless:true})
const context = await browser.newContext({viewport:{width:1440,height:900},serviceWorkers:'block'})
const errors=[]
try {
  await context.route('**/*',r=>{
    const u=new URL(r.request().url())
    return u.origin!==base.origin || u.pathname.startsWith('/api/') || !['GET','HEAD'].includes(r.request().method()) ? r.abort() : r.continue()
  })
  const page=await context.newPage()
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base.origin+'/catalog')
  await page.locator('main a[href="/catalog/all"]').waitFor()
  assert.equal(await page.locator('h1').innerText(),'Каталог Perfect Skin')
  assert.equal(await page.locator('h1').evaluate(e=>getComputedStyle(e).textAlign),'center')
  assert.equal(await page.locator('h1 [data-catalog-word]').evaluate(e=>getComputedStyle(e).fontWeight),'300')
  assert.equal(await page.locator('h1 strong').evaluate(e=>getComputedStyle(e).fontWeight),'700')
  const categories=await page.evaluate(async()=> (await (await fetch('/snapshot/catalog.json')).json()).categoriesTree)
  for (const category of categories) {
    assert.equal(await page.locator(`main a[href="/catalog/${category.slug}"]`).count(),1,`Missing real category: ${category.slug}`)
  }
  const allBox=await page.locator('main a[href="/catalog/all"]').boundingBox()
  assert(Math.abs(allBox.width-allBox.height)<2,'All tile must be square on desktop')
  const gridWidth=await page.locator('.catalog-editorial').evaluate(e=>e.getBoundingClientRect().width)
  assert(Math.abs(allBox.width-(gridWidth-36)/4)<2,'All tile must fill its grid span in WebKit too')
  assert(await page.locator('main a[href="/catalog/all?sort=popular"]').isVisible(),'Missing bestsellers')
  assert.equal(await page.locator('.catalog-packshot').count(),3,'Three real packshots')
  const active=()=>page.locator('.catalog-packshot[data-active="true"]').getAttribute('src')
  const initial=await active()
  await page.waitForTimeout(5300)
  assert.notEqual(await active(),initial,'Timed crossfade')
  await page.getByRole('button',{name:'Приостановить смену товаров'}).click()
  const paused=await active()
  await page.waitForTimeout(5300)
  assert.equal(await active(),paused,'User pause must persist')
  assert.equal(await page.locator('.catalog-bestsellers video').count(),1,'Existing project video')
  await page.getByRole('button',{name:'Продолжить смену товаров'}).click()
  const beforeResume=await active()
  await page.waitForTimeout(5300)
  assert.notEqual(await active(),beforeResume,'Resume must restore timed changes')
  const allLink=page.locator('main a[href="/catalog/all"]')
  await page.keyboard.press('Tab') // Establish keyboard modality, not mouse-induced focus.
  await allLink.focus()
  assert(await allLink.evaluate(e=>e.matches(':focus-visible') && parseFloat(getComputedStyle(e).outlineOffset)<0),'Cover link focus must be drawn inside overflow-hidden tile')
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.waitForTimeout(350)
  assert(await page.locator('.catalog-bestsellers video').evaluate(v=>v.paused),'Reduced-motion pauses video')
  const reduced=await active()
  await page.waitForTimeout(5300)
  assert.equal(await active(),reduced,'Reduced-motion static image')
  await page.locator('main a[href="/catalog/all"]').click()
  await page.waitForURL('**/catalog/all')
  assert.equal(await page.locator('h1').innerText(),'Каталог Perfect Skin')
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({passed:true,engine,checks:['index heading','all heading','weights','center'],errors}))
} finally { await browser.close() }
